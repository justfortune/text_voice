CLAUSE_END = _rx(r"[.!?…;]")


def _clause(text, pos):
    """Границы предложения/части фразы вокруг позиции pos: контекст ищется только внутри."""
    a = 0
    for m in CLAUSE_END.finditer(text, 0, pos):
        a = m.end()
    m = CLAUSE_END.search(text, pos)
    b = m.start() if m else len(text)
    return a, b


def _negated(text, a, s, e):
    """Отрицание/сравнение/сослагательность перед словом или «бы» после него."""
    return bool(NEG.search(text[max(a, s - 26):s]) or NEG_AFTER.match(text[e:e + 24]))


def scan_sfx(rows, a, b):
    """Звуки-события во фразах a..b -> [dict(kind='sfx', i, pos (доля в тексте), len, label, conf, why)]."""
    # абзацы с прямой речью: слова автора там — пояснение к реплике («крикнул он»), голосовые звуки не ставим
    has_speech = set()
    for i in range(max(0, a - 3), min(len(rows), b + 4)):
        if rows[i].get("kind") == "speech":
            has_speech.add((rows[i].get("chapter"), rows[i].get("para")))
    out, last = [], {}
    for i in range(a, b + 1):
        r = rows[i]
        if r.get("kind") != "narr":
            continue
        text = r.get("text") or ""
        if len(text) < 8:
            continue
        in_dialog = (r.get("chapter"), r.get("para")) in has_speech
        found, spans = [], []

        def add(label, dur, s, e, conf, weak=False):
            if any(s < y and e > x for x, y in spans):
                return
            spans.append((s, e))
            found.append(dict(label=label, len=dur, s=s, e=e, conf=conf, weak=weak))

        for m in IMP.finditer(text):                           # «раздался …»
            ca, cb = _clause(text, m.start())
            if _negated(text, ca, m.start(), m.end()):
                continue
            seg0, seg1 = max(ca, m.start() - 60), min(cb, m.end() + 60)
            best = None
            for rx, lab, d in IMP_NOUN:
                k = rx.search(text, seg0, seg1)
                if k and (best is None or abs(k.start() - m.start()) < abs(best[0].start() - m.start())):
                    best = (k, lab, d)
            if best:
                k, lab, d = best
                add(lab, d, min(m.start(), k.start()), max(m.end(), k.end()), .9)
        for lab, dur, trig, ctx, no, conf, fl in SFX:
            if "v" in fl and in_dialog:
                continue
            for m in trig.finditer(text):
                ca, cb = _clause(text, m.start())
                cl = text[ca:cb]
                if ctx is not None:
                    kx = ctx.search(cl)
                    if not kx or _compared(cl, 0, kx.start()):  # «закрылся за ним, как дверь» — двери тут нет
                        continue
                if no is not None and no.search(cl):
                    continue
                if _negated(text, ca, m.start(), m.end()) or _compared(text, ca, m.start()):
                    continue
                add(lab, dur, m.start(), m.end(), conf, "w" in fl)
        strong = [f for f in found if not f["weak"]]
        found = sorted(strong or found[:1], key=lambda f: (-f["conf"], f["s"]))[:2]
        for f in sorted(found, key=lambda f: f["s"]):
            if last.get(f["label"], -99) >= i - 1:              # то же самое подряд — одно событие
                last[f["label"]] = i
                continue
            last[f["label"]] = i
            s0, s1 = max(0, f["s"] - 28), min(len(text), f["e"] + 28)
            out.append(dict(kind="sfx", i=i, pos=round(min(1.0, f["e"] / max(1, len(text))), 3), len=f["len"],
                            label=f["label"], conf=f["conf"],
                            why=("…" if s0 else "") + text[s0:s1].strip() + ("…" if s1 < len(text) else "")))
    return out


def _scenes(rows, a, b):
    """Сцены во фразах a..b: главы и разрывы внутри них («* * *», заголовки) -> [(a, b)]."""
    out, s = [], a
    for i in range(a + 1, b + 1):
        new = rows[i].get("chapter") != rows[i - 1].get("chapter") or rows[i].get("kind") == "head" \
            or re.fullmatch(r"[\s*#~·•–—-]{1,12}", rows[i].get("text") or "x") is not None
        if new:
            if i - 1 >= s:
                out.append((s, i - 1))
            s = i
    out.append((s, b))
    return [(x, y) for x, y in out if y >= x]


def scan_amb(rows, a, b, dur_of=None):
    """Фон (обстановка): от фразы с приметой на длину по умолчанию, но не дальше конца сцены."""
    dur_of = dur_of or (lambda i: max(1.0, len(rows[i].get("text") or "") / 14.0))
    out = []
    for sa, sb in _scenes(rows, a, b):
        busy_until = {}
        for i in range(sa, sb + 1):
            r = rows[i]
            if r.get("kind") != "narr":
                continue
            text = r.get("text") or ""
            for lab, dur, trig, no, conf in AMB:
                if busy_until.get(lab, -1) >= i:
                    continue
                m = trig.search(text)
                if not m:
                    continue
                ca, cb = _clause(text, m.start())
                if (no is not None and no.search(text[ca:cb])) or _negated(text, ca, m.start(), m.end()) \
                        or _compared(text, ca, m.start()):
                    continue
                j, t = i, 0.0
                while j < sb and t < dur:
                    t += dur_of(j)
                    j += 1
                # примета повторяется дальше в сцене — фон тянется до последнего упоминания (плюс запас)
                k = j
                while k <= sb and k - j < 40:
                    if rows[k].get("kind") == "narr" and trig.search(rows[k].get("text") or ""):
                        j, t2 = k, 0.0
                        while j < sb and t2 < dur / 2:
                            t2 += dur_of(j)
                            j += 1
                        k = j
                    k += 1
                j = min(j, sb)
                busy_until[lab] = j
                s0, s1 = max(0, m.start() - 28), min(len(text), m.end() + 28)
                out.append(dict(kind="amb", i=i, pos=0.0, end_i=j, len=None, label=lab, conf=conf,
                                why=("…" if s0 else "") + text[s0:s1].strip() + ("…" if s1 < len(text) else "")))
    return out


def scan_music(rows, a, b, dur_of=None):
    """Музыка по настроению сцен: окна по ~10 фраз, соседние окна с одним настроением сливаются."""
    dur_of = dur_of or (lambda i: max(1.0, len(rows[i].get("text") or "") / 14.0))
    out = []
    for sa, sb in _scenes(rows, a, b):
        wins, i = [], sa
        while i <= sb:
            j, sec = i, 0.0
            while j <= sb and (sec < 40.0 or j - i < 6):
                sec += dur_of(j)
                j += 1
            wins.append((i, j - 1, sec))
            i = j
        if len(wins) > 1 and wins[-1][2] < 15.0:                # хвостик сцены — к предыдущему окну
            x = wins.pop()
            wins[-1] = (wins[-1][0], x[1], wins[-1][2] + x[2])
        labelled = []
        for wa, wb, sec in wins:
            text = " ".join(rows[k].get("text") or "" for k in range(wa, wb + 1))
            words = max(1, len(WORD.findall(text)))
            best = None
            for lab, rx in MOOD.items():
                hits = rx.findall(text)
                kinds = len(set(h.lower()[:5] for h in hits))
                rate = len(hits) * 1000.0 / words
                if len(hits) >= MOOD_MIN_HITS and kinds >= 3 and rate >= MOOD_MIN_RATE:
                    if best is None or rate > best[1]:
                        best = (lab, rate, hits)
            labelled.append((wa, wb, sec, best))
        k = 0
        while k < len(labelled):
            wa, wb, sec, best = labelled[k]
            if best is None:
                k += 1
                continue
            lab, rate, hits = best
            j = k + 1
            while j < len(labelled) and labelled[j][3] is not None and labelled[j][3][0] == lab:
                wb, sec = labelled[j][1], sec + labelled[j][2]
                hits = hits + labelled[j][3][2]
                rate = max(rate, labelled[j][3][1])
                j += 1
            if sec >= MOOD_MIN_SEC:
                top = []
                for h in hits:
                    h = h.lower()
                    if h not in top:
                        top.append(h)
                out.append(dict(kind="mus", i=wa, pos=0.0, end_i=wb, len=None, label=lab,
                                conf=round(min(.9, .35 + rate / 120.0), 2), why="слова сцены: " + ", ".join(top[:8])))
            k = j
    return out


def scan(rows, a, b, dur_of=None, kinds=("sfx", "amb", "mus")):
    """Все заглушки для фраз a..b. dur_of(i) — длительность фразы в секундах (если есть готовая лента)."""
    out = []
    if "sfx" in kinds:
        out += scan_sfx(rows, a, b)
    if "amb" in kinds:
        out += scan_amb(rows, a, b, dur_of)
    if "mus" in kinds:
        out += scan_music(rows, a, b, dur_of)
    out.sort(key=lambda c: (c["i"], c["pos"], c["kind"]))
    return out


def labels():
    """Все подписи, которые умеет ставить распознаватель: {вид: [подписи]} — для списка в редакторе."""
    sfx = []
    for lab in [x[0] for x in SFX] + [x[1] for x in IMP_NOUN]:
        if lab not in sfx:
            sfx.append(lab)
    return {"sfx": sfx, "amb": [x[0] for x in AMB], "mus": list(MOOD)}


